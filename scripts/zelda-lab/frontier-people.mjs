#!/usr/bin/env node
// Bake the frontier NPCs' isometric frames from their poses and classic sprite names.
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gzipSync } from 'node:zlib'
import { buildSync } from 'esbuild'

const root = fileURLToPath(new URL('../../themes/zelda/render/', import.meta.url))
const bundle = buildSync({
  stdin: {
    contents: `
      export { FRONTIER_NPC_NAMES, FRONTIER_CREATURES, FRONTIER_BOSSES, FRONTIER_RAW, CREATURE_POSES } from './frontierSprites'
      export { peoplePose } from './iso/frontierArt/people'
      export { creaturePose, grok } from './iso/frontierArt/creatures'
      export { rasterThing } from './iso/props'
      export { rowsHash } from './iso/folk'
    `,
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  format: 'esm',
  write: false,
})
const { FRONTIER_NPC_NAMES, FRONTIER_CREATURES, FRONTIER_BOSSES, FRONTIER_RAW, CREATURE_POSES, peoplePose, creaturePose, grok, rasterThing, rowsHash } =
  await import('data:text/javascript;base64,' + Buffer.from(bundle.outputFiles[0].contents).toString('base64'))

const letters = [...Array(94)].map((_, i) => String.fromCharCode(33 + i)).filter(ch => ch !== '.')

function frame(build, palette) {
  const { w, h, ax, ay, albedo } = rasterThing(build)
  let left = w
  let right = -1
  let top = h
  let bottom = -1
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    if (!albedo[(y * w + x) * 4 + 3]) continue
    left = Math.min(left, x)
    right = Math.max(right, x)
    top = Math.min(top, y)
    bottom = Math.max(bottom, y)
  }
  if (right < 0) throw new Error('Empty isometric pose')
  const rows = []
  for (let y = top; y <= bottom; y++) {
    let row = ''
    for (let x = left; x <= right; x++) {
      const i = (y * w + x) * 4
      if (!albedo[i + 3]) { row += '.'; continue }
      const color = '#' + Buffer.from(albedo.subarray(i, i + 3)).toString('hex')
      if (!palette.has(color)) {
        palette.set(color, letters[palette.size] ?? String.fromCharCode(256 + palette.size - letters.length))
      }
      row += palette.get(color)
    }
    rows.push(row)
  }
  return { ax: ax - left, ay: ay - top, rows }
}

const families = [...FRONTIER_NPC_NAMES, ...FRONTIER_CREATURES].map(name => {
  const pal = new Map()
  const src = {}
  const frames = {}
  const draw = FRONTIER_NPC_NAMES.includes(name) ? peoplePose : creaturePose
  for (const step of [0, 1]) {
    for (const dir of ['up', 'down', 'side']) {
      const sprite = `${name}_${dir}_${step}`
      src[sprite] = rowsHash(FRONTIER_RAW[sprite])
    }
    frames[`front_${step}`] = frame(draw(name, false, step), pal)
    frames[`back_${step}`] = frame(draw(name, true, step), pal)
  }
  for (const pose of CREATURE_POSES[name] ?? []) {
    const sprite = `${name}_${pose}`
    src[sprite] = rowsHash(FRONTIER_RAW[sprite])
    frames[`front_${pose}`] = frame(draw(name, false, pose.endsWith('b') ? 1 : 0, pose), pal)
  }
  return [name, { pal: Object.fromEntries([...pal].map(([color, ch]) => [ch, color])), src, frames }]
})

const json = JSON.stringify
const pack = list => json(gzipSync(json(Object.fromEntries(list))).toString('base64'))
writeFileSync(resolve(root, 'iso/frontierArt/peopleData.ts'), `// Generated by scripts/zelda-lab/frontier-people.mjs.
import type { FolkFamily } from '../folkArt'
import { unpackArt } from './packed'

export const FRONTIER_FOLK_ART = unpackArt<Record<string, FolkFamily>>(${pack(families.filter(([name]) => !FRONTIER_BOSSES.includes(name)))})

export const FRONTIER_BOSS_ART = unpackArt<Record<string, FolkFamily>>(${pack(families.filter(([name]) => FRONTIER_BOSSES.includes(name)))})
`)
console.log(`Baked ${families.length} frontier figures`)

// The same 3D rig is also available to Blender, without embedding a model in the game.
if (process.argv[2]) {
  const guide = Object.fromEntries(CREATURE_POSES.grok.map(pose => {
    const shapes = []
    const record = (kind) => (...args) => {
      const mat = args.pop()
      shapes.push({ kind, args, mat: typeof mat === 'string' ? mat : 'stone' })
    }
    grok(pose, 0)({ ball: record('ball'), box: record('box'), post: record('post') })
    return [pose, shapes]
  }))
  writeFileSync(process.argv[2], json(guide))
}
