# emit.py: build/*.json -> themes/zelda/render/iso/thingArt.ts (generated)
import json, glob, os, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from kitlib import ISO, work
R = work('things')
OUT = os.path.join(ISO, 'thingArt.ts')
sp = json.load(open(f'{R}/classic/sprites.json'))['sprites']
def fnv(rows):
    h = 0x811c9dc5
    for ch in '\n'.join(rows):
        h ^= ord(ch); h = (h * 0x01000193) & 0xffffffff
    return '%08x' % h
# the classic sprites each thing was drawn from (its identity), as the game showed them with the live pack applied
SRC = {'van': ['prop_van'], 'tent': ['prop_tent'], 'fort': ['prop_fort'], 'bike': ['prop_bike'], 'mast': ['prop_mast'], 'mast_on': ['prop_mast_on'],
       'tank_0': ['prop_tank_0'], 'tank_1': ['prop_tank_1'], **{f'campfire_{i}': [f'prop_campfire_{i}'] for i in range(3)},
       **{f'bonfire_{i}': [f'bonfire_{i}'] for i in range(3)}}
J = lambda v: json.dumps(v, ensure_ascii=False)
parts = []
BUILT = {os.path.basename(f)[:-5]: json.load(open(f)) for f in sorted(glob.glob(f'{R}/build/*.json'))}
# a frame made as a pixel edit of a drawing shares that drawing's normals and depth (`like`)
LIKE = {}
for tid, t in BUILT.items():
    if t.get('edit'):
        base = next((b for b, u in BUILT.items() if b != tid and u['frame'] == t['frame'] and not u.get('edit') and u['nrows'] == t['nrows'] and u['deep'] == t['deep']), None)
        if base is None:
            base = next((b for b, u in BUILT.items() if b < tid and u['frame'] == t['frame'] and u['nrows'] == t['nrows'] and u['deep'] == t['deep'] and b not in LIKE), None)
        if base: LIKE[tid] = base
for tid, t in BUILT.items():
    src = {n: fnv(sp[n]['rows']) for n in SRC.get(tid, [])}
    L = [f'  {J(tid)}: {{', f'    w: {t["w"]}, h: {t["h"]}, ax: {t["ax"]}, ay: {t["ay"]},',
         f'    // drawn on sheet {t["sheet"]} ({t["frame"]}, pitch {t["pitch"]}){", a pixel edit: " + t["edit"] if t.get("edit") else ""}',
         f'    src: {J(src)},', f'    pal: {J(t["pal"])},', f'    glow: {J(t["glow"])},',
         '    rows: [', *[f'      {J(r)},' for r in t['rows']], '    ],']
    if tid in LIKE: L += [f'    like: {J(LIKE[tid])},', '  },']
    else: L += [f'    npal: {J(t["npal"])},', '    nrows: [', *[f'      {J(r)},' for r in t['nrows']], '    ],', f'    deep: {J(t["deep"])},', '  },']
    parts.append('\n'.join(L))
HEAD = '''/**
 * The things drawn by hand for the isometric view (part 23, 2026-11-25; read by `things.ts`). Each was built as a
 * guide from a few solids seen as this view sees the world, and Codex `image_gen` drew it over that guide as pixel art;
 * the drawing was cut at the grid it was drawn on, with a hard alpha. Every colour here is the drawing's.
 * Generated by scripts/zelda-lab/codex/things/ (build.py and emit.py). Per thing:
 * - `rows`: palette letters, one row a line, `.` clear; `pal` and `glow` (how much a colour glows by itself);
 * - `nrows`: which way each px faces, a letter (char code − 48) into `npal` (rgb: right, up, toward the viewer);
 * - `deep`: base64, a byte a px: how near it lies (`depthCode` in `props.ts`), from the guide;
 * - `like`: a frame made as a pixel edit of another's drawing (a lamp lit, bubbles risen, bulbs dimmed) has its normals and depth;
 * - (ax, ay): the point of ground under the thing's middle; `src`: the hash (`rowsHash`) of each classic sprite's rows
 *   it was drawn from, as the game showed them with the studio's live pack applied.
 * Edit by redrawing and regenerating, never the hashes by hand.
 */
export interface ThingArt {
  w: number
  h: number
  ax: number
  ay: number
  src?: Record<string, string>
  pal: Record<string, string>
  glow: Record<string, number>
  rows: string[]
  /** A pixel edit of another thing's drawing (a frame): its normals and depth are that one's. */
  like?: string
  npal?: string[]
  nrows?: string[]
  deep?: string
}

export const THING_ART: Record<string, ThingArt> = {
'''
open(OUT, 'w').write(HEAD + '\n'.join(parts) + '\n}\n')
print('wrote', OUT, os.path.getsize(OUT) // 1024, 'KB', len(parts), 'things')
