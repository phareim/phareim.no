function hurt(rows, [crease, lids], size) {
  const grid = rows.map(row => [...row])
  for (const [x, y, w, h, fill, dark] of lids) {
    for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) {
      const row = grid[y + j]
      if (row?.[x + i] && row[x + i] !== '.') row[x + i] = j === Math.floor(h / 2) - (i % 3 === 0 ? 1 : 0) ? dark : fill
    }
  }
  const amount = size === 2 ? 2 : 1
  grid.splice(crease, amount)
  for (let i = 0; i < amount; i++) grid.unshift(Array(rows[0].length).fill('.'))
  return grid.map((row, y) => {
    // The shoulders and head recoil a little farther than the feet.
    const shift = y < crease / 2 ? amount : y < crease + amount ? 1 : 0
    return '.'.repeat(shift) + row.slice(0, row.length - shift).join('')
  })
}

const classic = {}
const iso = {}
for (const [name, p] of Object.entries(poses)) {
  const src = {}
  const frames = {}
  const pose = (cfg, facing, classicName) => {
    const from = FOLK_ART[name].frames[facing + '_0']
    const rows = hurt(SPRITES[cfg.from].rows, cfg.classic, 1)
    classic[classicName] = rows
    src[classicName] = rowsHash(rows)
    frames[facing + '_hurt'] = { ...from, rows: hurt(from.rows, cfg.iso, 2) }
  }
  pose(p, 'front', name + '_hurt')
  if (p.back) pose(p.back, 'back', name + '_up_hurt')
  iso[name] = { src, frames }
}
