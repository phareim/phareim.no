/**
 * `clip_heart` at half scale, the brightest of each 2×2 px kept: taking every other px breaks its one-px wire into
 * dashes.
 */
function halved(rows: readonly string[]): string[] {
  return Array.from({ length: rows.length / 2 }, (_, y) => Array.from({ length: rows[0]!.length / 2 }, (_, x) => {
    const four = [0, 1, 2, 3].map(i => rows[y * 2 + (i >> 1)]![x * 2 + (i & 1)]!)
    return four.includes('W') ? 'W' : four.includes('g') ? 'g' : four.filter(c => c === 'k').length > 1 ? 'k' : '.'
  }).join(''))
}
MAXIMIZER_RAW.hud_heart_clip = halved(MAXIMIZER_RAW.clip_heart!)
