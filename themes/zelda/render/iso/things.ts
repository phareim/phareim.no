/**
 * The things of the world drawn by hand for the isometric view (part 23, 2026-11-25): the Horizon van, the tents,
 * Luna's fort, the campfire, the beach bonfire and the tiki torches, the bikes, the radio mast, the labs' specimen
 * tanks, the beach's DJ booths (speakers, tables, the fairy lights), the furniture of the rooms (bookshelves, the sofa,
 * the desk, the glass table, plants, screen machines, the hut's bed and table), the labs' consoles, terminals and
 * workbenches, and the fountain in the square's pool. Pure: no canvas, no DOM.
 *
 * Each was built as a guide from a few solids (boxes, posts, balls, tubes) seen exactly as this view sees the world
 * (`props.ts`'s line of sight), and Codex `image_gen` drew it over that guide as pixel art, a pixel to the scene's
 * pixel. The guide gave each drawn pixel two things the drawing has not: which way the surface faces (so the lamps
 * and the sun light it, as the built things) and how near it lies (`depthCode`, so the van stands in the floor and
 * the hero walks behind and in front of it as of a counter). Every colour is the drawing's.
 *
 * `withThings(atlas)` packs them under the built things in the same atlas (the same two pictures, read texel by
 * texel), named `thing:<id>`; `view.ts` stands them through `stand()` like the built things while value `things` is
 * on: where an item of the classic painter names one (`Item.things` in `wild.ts`: the van, a booth's parts, the
 * bonfire), where a tile is one (`furnitureAt`: a run of furniture, a lab's console; the lab tanks and the beach's
 * torches in the view's own tile pass), and the `LANDMARKS`. Animations are frames by id (`campfire_0..2`), chosen
 * by the same clock as the classic art. The art is `thingArt.ts`, generated by the job's tools
 * (tmp/iso-figures-23/tools on the Mac).
 */
import { THING_ART, type ThingArt } from './thingArt'
import type { PropAtlas, PropSprite } from './props'
import { rowsHash } from './folk'
import { spriteRevision, spriteRows } from '../sheet'

/** The name a drawn thing stands under in the atlas. */
export const thingKey = (id: string): `thing:${string}` => `thing:${id}`

function bytes(b64: string): Uint8Array {
  const s = atob(b64)
  const out = new Uint8Array(s.length)
  for (let i = 0; i < s.length; i++) out[i] = s.charCodeAt(i)
  return out
}

const hex = (s: string): [number, number, number] => {
  const v = parseInt(s.replace('#', ''), 16)
  return [(v >> 16) & 255, (v >> 8) & 255, v & 255]
}

/** Paints one thing into the atlas at (ox, oy): colour, its depth in the colour's alpha, its normal and its glow. */
export function paintThing(t: ThingArt, albedo: Uint8ClampedArray, normal: Uint8ClampedArray, aw: number, ox: number, oy: number): void {
  const geo = t.like ? THING_ART[t.like]! : t
  const deep = bytes(geo.deep!)
  const pal = new Map(Object.entries(t.pal).map(([k, v]) => [k, hex(v)]))
  const npal = geo.npal!.map(hex)
  for (let y = 0; y < t.h; y++) {
    const row = t.rows[y]!
    const nrow = geo.nrows![y]!
    for (let x = 0; x < t.w; x++) {
      const ch = row[x]!
      if (ch === '.') continue
      const c = pal.get(ch)!
      const n = npal[nrow.charCodeAt(x) - 48]!
      const o = ((oy + y) * aw + ox + x) * 4
      albedo[o] = c[0]; albedo[o + 1] = c[1]; albedo[o + 2] = c[2]
      albedo[o + 3] = Math.max(1, deep[y * t.w + x]!)
      normal[o] = n[0]; normal[o + 1] = n[1]; normal[o + 2] = n[2]
      normal[o + 3] = Math.round((t.glow[ch] ?? 0) * 255)
    }
  }
}

let made: { from: PropAtlas; atlas: PropAtlas } | null = null
let expanded: { from: PropAtlas; extra: Record<string, ThingArt>; atlas: PropAtlas } | null = null

/** Pack the base art below the built things and extend it with the visible realm's kit. */
export function withThings(props: PropAtlas, extra?: Record<string, ThingArt>): PropAtlas {
  if (made?.from !== props) made = { from: props, atlas: packThings(props, THING_ART) }
  if (!extra) { expanded = null; return made.atlas }
  if (expanded?.from !== made.atlas || expanded.extra !== extra) {
    expanded = { from: made.atlas, extra, atlas: packThings(made.atlas, extra) }
  }
  return expanded.atlas
}

/** Pack into shelves with two clear pixels around each sprite. */
function packThings(props: PropAtlas, art: Record<string, ThingArt>): PropAtlas {
  const w = props.w
  const ids = Object.keys(art).sort((a, b) => art[b]!.h - art[a]!.h)
  const at: Record<string, [number, number]> = {}
  let x = 2
  let y = props.h + 2
  let shelf = 0
  for (const id of ids) {
    const t = art[id]!
    if (x + t.w + 2 > w) { x = 2; y += shelf + 2; shelf = 0 }
    at[id] = [x, y]
    x += t.w + 2
    shelf = Math.max(shelf, t.h)
  }
  const h = y + shelf + 2
  const albedo = new Uint8ClampedArray(w * h * 4)
  const normal = new Uint8ClampedArray(w * h * 4)
  albedo.set(props.albedo)
  normal.set(props.normal)
  const sprites: Record<string, PropSprite> = { ...props.sprites }
  for (const id of ids) {
    const t = art[id]!
    const [ox, oy] = at[id]!
    paintThing(t, albedo, normal, w, ox, oy)
    sprites[thingKey(id)] = { x: ox, y: oy, w: t.w, h: t.h, ax: t.ax, ay: t.ay, top: 0 }
  }
  return { w, h, albedo, normal, sprites: sprites as PropAtlas['sprites'] }
}

const fresh = new Map<string, boolean>()
let seen = -1

/**
 * Is a drawn thing still what the game shows: every classic sprite it was drawn from has the rows it had (the
 * studio's live pack applied)? A thing the studio has redrawn since is its classic card again, as a stale family
 * of the people is. A thing with no classic sprite (a booth's parts, painted in code) always is.
 */
export function thingFresh(id: string): boolean {
  const t = THING_ART[id]
  if (!t) return false
  if (seen !== spriteRevision()) { seen = spriteRevision(); fresh.clear() }
  let ok = fresh.get(id)
  if (ok === undefined) {
    ok = Object.entries(t.src ?? {}).every(([name, hash]) => rowsHash(spriteRows(name)) === hash)
    fresh.set(id, ok)
  }
  return ok
}

/** Does the view have a drawn thing by this id, still fresh. */
export const hasThing = (id: string): boolean => !!THING_ART[id] && thingFresh(id)

/** A piece of furniture drawn by hand, standing for a run of tiles indoors: which, and the point of ground under its middle (tiles). */
export interface FurniturePiece { id: string; x: number; y: number }

/**
 * The boxes that stand for a bed and a table in a room (2 × 2 tiles of counter, `n`), by map and top-left tile: the
 * classic art draws them as plain blocks, and this view gives them what they are.
 */
const FURNISHED: Record<string, Record<string, string>> = {
  hut: { '1,1': 'bed', '9,3': 'table' },
}

/** Where a room is, for `furnitureAt`: the map, whether it is one of Project Horizon's labs, and the animation's tick. */
export interface RoomAt { map: string; lab: boolean; /** Whole steps of the clock (the frames of a console's lights, a screen's colour). */ tick: number }

/**
 * Which piece drawn by hand stands for an indoor tile (part 23). In a room: a bookshelf `[` (one or two tiles), the
 * sofa `(` (three), the desk `w` (two), the glass table `~` (two), a potted plant `Y`, a machine with a screen `M`
 * (its colour moving on with the tick, as the classic one's), and a room's bed and table (`FURNISHED`). In a lab: a
 * control console `M` (its lights blinking), a terminal `S`, and a workbench `n` two tiles at a time. The run's first
 * tile gets the piece; `'part'` for its other tiles (their card goes too); null when this view has no piece for that
 * tile or run (a run of another length): its card stays.
 */
export function furnitureAt(tileOf: (x: number, y: number) => string, tx: number, ty: number, room: RoomAt): FurniturePiece | 'part' | null {
  const t = tileOf(tx, ty)
  const own = (id: string, x: number, y: number): FurniturePiece | null => (hasThing(id) ? { id, x, y } : null)
  if (room.lab) {
    if (t === 'M') return own(`console_${(room.tick + tx) % 2}`, tx + 0.5, ty + 0.5)
    if (t === 'S') return own('terminal', tx + 0.5, ty + 0.55)
    if (t !== 'n' || !hasThing('bench_2')) return null
    let x0 = tx
    while (tileOf(x0 - 1, ty) === 'n') x0--
    let n = 1
    while (tileOf(x0 + n, ty) === 'n') n++
    if (n % 2) return null
    return (tx - x0) % 2 ? 'part' : { id: 'bench_2', x: tx + 1, y: ty + 0.5 }
  }
  if (t === 'M') return own(`machine_${(room.tick + tx * 3) % 3}`, tx + 0.5, ty + 0.5)
  if (t === 'n') {
    for (const [dx, dy] of [[0, 0], [-1, 0], [0, -1], [-1, -1]] as const) {
      const id = FURNISHED[room.map]?.[`${tx + dx},${ty + dy}`]
      if (id) return !hasThing(id) ? null : dx === 0 && dy === 0 ? { id, x: tx + 1, y: ty + 1 } : 'part'
    }
    return null
  }
  if (t === 'Y') return own('plant', tx + 0.5, ty + 0.55)
  const run: Record<string, [string, number][]> = { '[': [['shelf_1', 1], ['shelf_2', 2]], '(': [['sofa_3', 3]], 'w': [['desk_2', 2]], '~': [['glass_2', 2]] }
  const kinds = run[t]
  if (!kinds) return null
  let x0 = tx
  while (tileOf(x0 - 1, ty) === t) x0--
  let n = 1
  while (tileOf(x0 + n, ty) === t) n++
  const id = kinds.find(([, len]) => len === n)?.[0]
  if (!id || !hasThing(id)) return null
  if (tx !== x0) return 'part'
  // (A shelf stands against the wall behind it; the rest in the middle of their row.)
  return { id, x: x0 + n / 2, y: ty + (t === '[' ? 0.3 : 0.5) }
}

