/**
 * The machines drawn by hand for the isometric view (part 25, 2026-11-26): the arcade cabinets, Petter's terminals and
 * the LOGIN console. Pure: no canvas, no DOM.
 *
 * Each was built as a guide from solids seen as this view sees the world, and Codex `image_gen` drew it over that guide as
 * pixel art: the NEW GAME cabinet as the master, every other cabinet a Codex edit of the master's drawing (its body
 * colours, trim and marquee) on the master's grid, so the styles share its normals and depth (`like`); the terminal and
 * the console on a sheet of their own. Their art (`machineArt.ts`, about 190 KB) is a chunk of its own, fetched the first
 * time the view is in a room with a machine (`machineArt`), as a realm's scenery is (`frontierArt/index.ts`); until it is
 * here, and for a cabinet whose style has no drawing, the classic front stands on its plain box.
 *
 * The screens are the classic painter's, live: an exit's item names its screen regions (`Item.screens`), and `view.ts`
 * stands them in the glass of the drawing (`MACHINE_SCREENS`, measured per drawing, `machineGlass.ts`) where `screenFit`
 * puts them. The art is generated by the job's tools (tmp/iso-figures-25/tools on the Mac).
 */
import type { ThingArt } from './thingArt'
import { MACHINE_SCREENS } from './machineGlass'

export { MACHINE_SCREENS, MACHINE_FROM } from './machineGlass'

type Kit = Record<string, ThingArt>

/** The exit looks that stand as a machine drawn by hand. */
const LOOKS = new Set(['cabinet', 'terminal', 'console'])

/** Does a hand-made map have a machine (an exit of a machine's look) for this view to stand drawn? */
export function hasMachines(def: { marks?: Record<string, { ent?: { t?: string; look?: string } }> } | null | undefined): boolean {
  return !!def?.marks && Object.values(def.marks).some(m => m.ent?.t === 'exit' && LOOKS.has(m.ent.look ?? ''))
}

/** A fetch that failed (offline) is tried again after this long, not every frame. */
const RETRY_MS = 10_000
let art: Kit | undefined
let pending: Promise<Kit | undefined> | null = null
let failedAt = -Infinity

/** Fetch the machines' art; resolves to it, or undefined when the fetch failed. */
export function loadMachineArt(): Promise<Kit | undefined> {
  if (art) return Promise.resolve(art)
  if (!pending) {
    pending = import('./machineArt').then(
      m => { art = m.MACHINE_ART; pending = null; return art },
      () => { failedAt = Date.now(); pending = null; return undefined },
    )
  }
  return pending
}

/** The machines' art if it is here; otherwise undefined, and its fetch is started (once, or again after a failure). */
export function machineArt(): Kit | undefined {
  if (!art && !pending && Date.now() - failedAt > RETRY_MS) void loadMachineArt()
  return art
}

const merged = new WeakMap<Kit, Kit>()
/** A realm's kit with the machines' art beside it (the same object for the same kit, so the atlas is packed once). */
export function withMachines(kit: Kit | undefined, machines: Kit | undefined): Kit | undefined {
  if (!machines) return kit
  if (!kit) return machines
  let m = merged.get(kit)
  if (!m) { m = { ...kit, ...machines }; merged.set(kit, m) }
  return m
}

/**
 * Where a machine's live screen stands in its drawing's glass: the classic region (w × h classic px) at the largest whole
 * scale at which no more than a px of each edge goes (the edge's half of a doubled classic px), in the middle of the glass
 * box ([left column, top row at it, width, height], `MACHINE_SCREENS`). Returns the scale, the screen's left column and its
 * top row there (a box running down half a px a column with the front), its size in the drawing's px, and the classic px
 * cut from the region's left and top edges.
 */
export function screenFit(box: readonly [number, number, number, number], w: number, h: number): { S: number; c: number; r: number; sw: number; sh: number; du: number; dv: number } {
  const [c0, r0, gw, gh] = box
  const S = Math.max(1, Math.min(Math.floor((gw + 2) / w), Math.floor((gh + 2) / h)))
  const sw = Math.min(gw, S * w)
  const sh = Math.min(gh, S * h)
  const c = c0 + Math.floor((gw - sw) / 2)
  const r = r0 + (c - c0) / 2 + Math.floor((gh - sh) / 2)
  return { S, c, r, sw, sh, du: (S * w - sw) / 2 / S, dv: (S * h - sh) / 2 / S }
}

/** The glass boxes of a machine's drawing, or none. */
export const glassOf = (id: string): ReadonlyArray<readonly [number, number, number, number]> | undefined => MACHINE_SCREENS[id]
