/**
 * The machines drawn by hand for the isometric view (part 25, 2026-11-26): the arcade cabinets, Petter's terminals and
 * the LOGIN console; and the square's SLEEPER NEWS newsstand and NEW LOOK stall (part 26). Pure: no canvas, no DOM.
 *
 * Each was built as a guide from solids seen as this view sees the world, and Codex `image_gen` drew it over that guide as
 * pixel art: the NEW GAME cabinet as the master, every other cabinet a Codex edit of the master's drawing (its body
 * colours, trim and marquee) on the master's grid, so the styles share its normals and depth (`like`); the terminal and
 * the console on a sheet of their own. Their art (`machineArt.ts`, about 190 KB) is a chunk of its own, fetched the first
 * time the view is in a room with a machine (`machineArt`), as a realm's scenery is (`frontierArt/index.ts`); until it is
 * here, and for a cabinet whose style has no drawing, the classic front stands on its plain box. The newsstand's and the
 * stall's art (`stallArt.ts`, about 150 KB) is a second chunk, so the town fetches only it.
 *
 * The screens are the classic painter's, live: an exit's item names its screen regions (`Item.screens`), and `view.ts`
 * stands them in the glass of the drawing (`MACHINE_SCREENS`, measured per drawing, `machineGlass.ts`) where `screenFit`
 * puts them. The newsstand's and the stall's lit signs and the stall's mirror are such regions too, and the people behind
 * the stall's counter cards of their own (`ThingScreen.stand`); the stall, too large for one Codex sheet, is four drawings
 * that stand together (roof, back wall, counter, a side wall twice). A map packs only the drawings its looks bring
 * (`machineLooks`, `machineKit`). The art is generated by the jobs' tools (tmp/iso-figures-25/tools and
 * tmp/iso-figures-26/tools on the Mac).
 */
import type { ThingArt } from './thingArt'
import { MACHINE_SCREENS } from './machineGlass'

export { MACHINE_SCREENS, MACHINE_FROM } from './machineGlass'

type Kit = Record<string, ThingArt>

/** The art's chunks: part 25's machines, and part 26's newsstand and stall (the town fetches only those). */
const CHUNKS = {
  machines: () => import('./machineArt').then(m => m.MACHINE_ART),
  stalls: () => import('./stallArt').then(m => m.STALL_ART),
} satisfies Record<string, () => Promise<Kit>>
type Chunk = keyof typeof CHUNKS

/**
 * The exit looks that stand drawn by hand: the chunk each one's drawings are in, and which of them it brings into the
 * atlas, so a map packs only its own (the square's newsstand and NEW LOOK stall do not bring the arcade's cabinets).
 */
const KIT_OF: Record<string, { chunk: Chunk; has: (id: string) => boolean }> = {
  cabinet: { chunk: 'machines', has: id => id.startsWith('cab_') },
  terminal: { chunk: 'machines', has: id => id === 'home_terminal' },
  console: { chunk: 'machines', has: id => id === 'login_console' },
  kiosk: { chunk: 'stalls', has: id => id === 'kiosk' },
  stall: { chunk: 'stalls', has: id => id.startsWith('look_') || id.startsWith('kata_') },
}

type MapMarks = { marks?: Record<string, { ent?: { t?: string; look?: string } }> } | null | undefined

/** The looks of a hand-made map's exits that stand drawn by hand, sorted and joined by '+' ('' none). */
export function machineLooks(def: MapMarks): string {
  if (!def?.marks) return ''
  const looks = new Set<string>()
  for (const m of Object.values(def.marks)) if (m.ent?.t === 'exit' && m.ent.look && m.ent.look in KIT_OF) looks.add(m.ent.look)
  return [...looks].sort().join('+')
}

/** Does a hand-made map have a machine (an exit of a machine's look) for this view to stand drawn? */
export function hasMachines(def: MapMarks): boolean {
  return machineLooks(def) !== ''
}

/** A fetch that failed (offline) is tried again after this long, not every frame. */
const RETRY_MS = 10_000
const art: Partial<Record<Chunk, Kit>> = {}
const pending: Partial<Record<Chunk, Promise<Kit | undefined>>> = {}
const failedAt: Record<Chunk, number> = { machines: -Infinity, stalls: -Infinity }

function load(c: Chunk): Promise<Kit | undefined> {
  if (art[c]) return Promise.resolve(art[c])
  return (pending[c] ??= CHUNKS[c]().then(
    k => { art[c] = k; delete pending[c]; return k },
    () => { failedAt[c] = Date.now(); delete pending[c]; return undefined },
  ))
}

/** Fetch all the machines' art (the lab and the tests); resolves to it, or undefined when a fetch failed. */
export async function loadMachineArt(): Promise<Kit | undefined> {
  const kits = await Promise.all((Object.keys(CHUNKS) as Chunk[]).map(load))
  return kits.every(Boolean) ? Object.assign({}, ...kits) as Kit : undefined
}

const chunksOf = (looks: string): Chunk[] => [...new Set(looks.split('+').filter(l => l in KIT_OF).map(l => KIT_OF[l]!.chunk))]

/**
 * Is the art for these looks here? If not, its fetch is started (once, or again after a failure) and the answer is no;
 * with no looks, whether part 25's machines are (the old question).
 */
export function machineArt(looks = 'cabinet'): boolean {
  let here = true
  for (const c of chunksOf(looks)) {
    if (art[c]) continue
    here = false
    if (!pending[c] && Date.now() - failedAt[c] > RETRY_MS) void load(c)
  }
  return here
}

const picked = new Map<string, Kit>()
/** The drawings a map's looks (`machineLooks`) bring, once their art is here (the same object for the same looks). */
export function machineKit(looks: string): Kit | undefined {
  if (!looks || !machineArt(looks)) return undefined
  let k = picked.get(looks)
  if (!k) {
    const want = looks.split('+').map(l => KIT_OF[l]).filter(Boolean)
    k = {}
    for (const w of want) for (const [id, t] of Object.entries(art[w!.chunk]!)) if (w!.has(id)) k[id] = t
    picked.set(looks, k)
  }
  return k
}

const merged = new WeakMap<Kit, WeakMap<Kit, Kit>>()
/** A realm's kit with the machines' art beside it (the same object for the same two, so the atlas is packed once). */
export function withMachines(kit: Kit | undefined, machines: Kit | undefined): Kit | undefined {
  if (!machines) return kit
  if (!kit) return machines
  let byKit = merged.get(kit)
  if (!byKit) { byKit = new WeakMap(); merged.set(kit, byKit) }
  let m = byKit.get(machines)
  if (!m) { m = { ...kit, ...machines }; byKit.set(machines, m) }
  return m
}

/**
 * Where a machine's live screen stands in its drawing's glass: the classic region (w × h classic px) at the largest whole
 * scale at which no more than a px of each edge goes (the edge's half of a doubled classic px), in the middle of the glass
 * box ([left column, top row at it, width, height], `MACHINE_SCREENS`). Returns the scale, the screen's left column and its
 * top row there (a box running down half a px a column with the front), its size in the drawing's px, and the classic px
 * cut from the region's left and top edges.
 */
export function screenFit(box: readonly [number, number, number, number], w: number, h: number): { S: number; c: number; r: number; sw: number; sh: number; du: number; dv: number } {
  const [c0, r0, gw, gh] = box
  const S = Math.max(1, Math.min(Math.floor((gw + 2) / w), Math.floor((gh + 2) / h)))
  const sw = Math.min(gw, S * w)
  const sh = Math.min(gh, S * h)
  const c = c0 + Math.floor((gw - sw) / 2)
  const r = r0 + (c - c0) / 2 + Math.floor((gh - sh) / 2)
  return { S, c, r, sw, sh, du: (S * w - sw) / 2 / S, dv: (S * h - sh) / 2 / S }
}

/** The glass boxes of a machine's drawing, or none. */
export const glassOf = (id: string): ReadonlyArray<readonly [number, number, number, number]> | undefined => MACHINE_SCREENS[id]
