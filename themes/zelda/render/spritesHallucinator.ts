export const HALLUCINATOR_SPRITES: Record<string, string[]> = Object.fromEntries(
  Object.entries(HALLUCINATOR_RAW).map(([name, rows]) => {
    // (The ghost is a popped body's last of it: pale, as the puff round it.)
    const hues = name === 'hallu_ghost' ? { c: 'W' } as Record<string, string> : HUES
    return [name, rows.map(row => [...row].map(ch => hues[ch] ?? ch).join(''))]
  }),
)
